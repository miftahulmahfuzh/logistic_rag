"""Generate the holdout annual report: a different fictional company, UK spelling, a table that spans
two pages and one chart image. Usage: uv run python scripts/make_holdout_pdf.py [out.pdf]

The PDF is generated, not committed. The retrieval code is never tuned on it; see eval/questions_holdout.yaml.
"""

import sys
from pathlib import Path

import pymupdf

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from tests.pdfmaker import draw_table  # noqa: E402

COMPANY = "Northmere Wind and Solar plc"
BODY, HEAD = 10, 16
SITE_HEADER = ["Site", "Technology", "Capacity (MW)", "Availability (%)"]
SITES = [
    ["Kelling Down", "Solar", "62", "97.1"],
    ["Harrowgate Moor", "Onshore wind", "118", "95.4"],
    ["Brannock Ridge", "Onshore wind", "96", "91.2"],
    ["Skerry Bank", "Offshore wind", "342", "94.8"],
    ["Dunmere Flats", "Offshore wind", "410", "93.6"],
    ["Fenwick", "Onshore wind", "74", "89.7"],
    ["Ottermouth", "Solar", "48", "98.0"],
    ["Carrow Hill", "Onshore wind", "131", "92.5"],
    ["Lowther Scar", "Onshore wind", "88", "96.3"],
    ["Penhallow", "Solar", "55", "97.6"],
    ["Greyfell", "Onshore wind", "109", "90.4"],
    ["Westerleigh Sands", "Offshore wind", "276", "95.0"],
    ["Marram Point", "Offshore wind", "188", "92.1"],
    ["Tarn Hollow", "Onshore wind", "67", "93.2"],
    ["Ashby Fen", "Solar", "81", "96.8"],
]
FINANCIALS = [
    ["Measure", "2024", "2025"],
    ["Turnover", "380", "412"],
    ["Operating profit", "71", "79"],
    ["Profit after tax", "52", "58"],
    ["Capital investment", "156", "201"],
    ["Net borrowings", "288", "312"],
    ["Gearing (%)", "41", "39"],
    ["Dividend per share (pence)", "10.4", "11.2"],
]
GENERATION = [("Onshore wind", 1240), ("Offshore wind", 1780), ("Solar", 395)]


def chart_png() -> bytes:
    """Bar chart drawn with PyMuPDF primitives on a scratch page, rendered to PNG."""
    scratch = pymupdf.open()
    page = scratch.new_page(width=420, height=240)
    page.insert_text((14, 22), "Electricity generated by technology, 2025", fontsize=12)
    page.insert_text((14, 38), "GWh", fontsize=9)
    base, top = 205, 60
    scale = (base - top) / max(v for _, v in GENERATION)
    for i, (name, value) in enumerate(GENERATION):
        x0 = 50 + i * 120
        page.draw_rect(
            pymupdf.Rect(x0, base - value * scale, x0 + 70, base),
            color=None,
            fill=(0.15, 0.45, 0.7),
        )
        page.insert_text((x0 + 12, base - value * scale - 5), f"{value:,}", fontsize=10)
        page.insert_text((x0 - 2, base + 14), name, fontsize=9)
    page.draw_line((40, base), (400, base), width=0.8)
    return page.get_pixmap(dpi=200).tobytes("png")


def prose(page: pymupdf.Page, y: float, text: str, height: float) -> float:
    rect = pymupdf.Rect(57, y, 538, y + height)
    if page.insert_textbox(rect, text, fontsize=BODY) < 0:
        raise ValueError(f"text overflows its box: {text[:40]!r}")
    return y + height


def heading(page: pymupdf.Page, y: float, text: str) -> float:
    page.insert_text((57, y + HEAD), text, fontsize=HEAD)
    return y + HEAD + 14


def build(path: Path) -> None:
    doc = pymupdf.open()

    def new_page() -> pymupdf.Page:
        page = doc.new_page(width=595, height=842)
        page.insert_text((57, 35), f"{COMPANY} | Annual Report 2025", fontsize=8)
        page.insert_text(
            (57, 820), f"{COMPANY}  Annual Report 2025  Page {doc.page_count}", fontsize=8
        )
        return page

    p = new_page()
    p.insert_text((57, 200), COMPANY, fontsize=28)
    p.insert_text((57, 240), "Annual Report and Accounts 2025", fontsize=18)
    prose(
        p,
        290,
        f"{COMPANY} generates electricity from onshore wind, offshore wind and solar sites across the "
        "United Kingdom and Ireland. Registered office: Leeds, England. Established 2011.\n\n"
        "This is a fictional company and document written for a software test. Any resemblance to a "
        "real company is coincidental.",
        110,
    )

    p = new_page()
    y = heading(p, 70, "Chair's statement")
    y = prose(
        p,
        y,
        "Dear shareholders,\n\n"
        "2025 was a year of steady delivery. Turnover reached £412 million, an increase of 8.4% on the "
        "£380 million recorded in 2024. The board recommends a full-year dividend of 11.2 pence per share, "
        "compared with 10.4 pence last year.\n\n"
        "Our workforce stands at 1,284 colleagues, up from 1,196 a year earlier. We completed the Kelling "
        "Down solar extension on schedule and within budget. The organisation remains committed to its "
        "decarbonisation programme and to colour-coded safety reporting at every site.\n\n"
        "Eleanor Whitcombe, Chair",
        200,
    )

    p = new_page()
    y = heading(p, 70, "Financial summary")
    y = prose(p, y, "Table 1: Financial summary (£ million unless stated)", 20)
    y = draw_table(p, 57, y + 4, FINANCIALS, w=150) + 14
    prose(
        p,
        y,
        "Net borrowings are measured after deducting cash and cash equivalents. The group's lenders set a "
        "gearing ceiling of 45%; gearing at the year end was 39%.",
        50,
    )

    p = new_page()
    y = heading(p, 70, "Operations")
    y = prose(
        p,
        y,
        "The portfolio comprises 15 sites with a combined installed capacity of 2,145 MW. A site is placed "
        "under performance review when its availability is below 92% in two consecutive years. "
        "Availability is reported for 2025 in Table 2 and the site register continues overleaf.",
        110,
    )
    y = prose(p, 540, "Table 2: Site register, installed capacity and availability, 2025", 20)
    draw_table(p, 57, y + 4, [SITE_HEADER, *SITES[:8]], w=120, h=18)

    p = new_page()
    draw_table(p, 57, 70, [SITE_HEADER, *SITES[8:]], w=120, h=18)
    y = heading(p, 270, "Health and safety")
    prose(
        p,
        y,
        "The lost-time injury rate was 0.31 per 200,000 hours worked, against a target of 0.40. No "
        "fatalities were recorded.",
        60,
    )

    p = new_page()
    y = heading(p, 70, "Generation")
    y = prose(
        p,
        y,
        "Total generation across the portfolio was 3,415 GWh. The split by technology is shown below.",
        40,
    )
    rect = pymupdf.Rect(57, y + 10, 57 + 420, y + 10 + 240)
    p.insert_image(rect, stream=chart_png())
    prose(p, rect.y1 + 8, "Figure 1: Electricity generated by technology, 2025 (GWh)", 20)

    p = new_page()
    y = heading(p, 70, "Outlook and governance")
    prose(
        p,
        y,
        "For 2026 we expect turnover growth of 6% to 8% and capital investment of about £230 million. We do "
        "not plan to acquire any offshore site in 2026; our focus is on raising output from existing sites.\n\n"
        "Connection charges for each site are set out in Appendix B.\n\n"
        "Board of directors: Eleanor Whitcombe (Chair) and Rhys Penmore (Chief Executive Officer).",
        200,
    )
    doc.save(path)


if __name__ == "__main__":
    out = (
        Path(sys.argv[1])
        if len(sys.argv) > 1
        else ROOT / "Northmere_Wind_Solar_Annual_Report_2025.pdf"
    )
    build(out)
    print(out)
